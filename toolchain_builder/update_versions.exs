Code.require_file("metadata.exs", __DIR__)
Code.require_file("crosstool_ng.exs", __DIR__)

defmodule ToolchainVersionUpdater do
  @output_path Path.join(__DIR__, "toolchain_versions.exs")
  @host_fragment Path.join(__DIR__, "defaults/linux_x86_64_defconfig")
  @excluded_version_keys MapSet.new([
                           "CT_CONFIG_VERSION",
                           "CT_TOOLCHAIN_PKGVERSION",
                           "CT_GLIBC_MIN_KERNEL_VERSION"
                         ])
  @preferred_order [
    "CT_GCC_VERSION",
    "CT_BINUTILS_VERSION",
    "CT_LINUX_VERSION",
    "CT_GLIBC_VERSION",
    "CT_MUSL_VERSION",
    "CT_GDB_VERSION",
    "CT_EXPAT_VERSION",
    "CT_GETTEXT_VERSION",
    "CT_GMP_VERSION",
    "CT_ISL_VERSION",
    "CT_LIBICONV_VERSION",
    "CT_MPC_VERSION",
    "CT_MPFR_VERSION",
    "CT_NCURSES_VERSION",
    "CT_ZLIB_VERSION"
  ]
  @labels %{
    "CT_GCC_VERSION" => "GCC",
    "CT_BINUTILS_VERSION" => "binutils",
    "CT_BISON_VERSION" => "bison",
    "CT_LINUX_VERSION" => "Linux headers",
    "CT_GLIBC_VERSION" => "glibc",
    "CT_MUSL_VERSION" => "musl",
    "CT_GDB_VERSION" => "GDB",
    "CT_EXPAT_VERSION" => "expat",
    "CT_GETTEXT_VERSION" => "gettext",
    "CT_GMP_VERSION" => "GMP",
    "CT_ISL_VERSION" => "ISL",
    "CT_LIBICONV_VERSION" => "libiconv",
    "CT_M4_VERSION" => "m4",
    "CT_MPC_VERSION" => "MPC",
    "CT_MPFR_VERSION" => "MPFR",
    "CT_NCURSES_VERSION" => "ncurses",
    "CT_ZLIB_VERSION" => "zlib"
  }

  def main(_argv) do
    ctng = CrosstoolNG.ensure!()

    version_metadata =
      ToolchainMetadata.targets()
      |> Enum.map(&resolve_toolchain_versions(&1, ctng))
      |> Enum.into(%{})

    File.write!(@output_path, render(version_metadata))
  end

  defp resolve_toolchain_versions(toolchain, ctng) do
    config_path = ToolchainMetadata.config_path(toolchain)
    merged_defconfig = merge_defconfigs(config_path)

    tmp_dir =
      System.tmp_dir!()
      |> Path.join("toolchain-version-#{toolchain}-#{System.unique_integer([:positive])}")

    try do
      File.mkdir_p!(tmp_dir)
      File.write!(Path.join(tmp_dir, "defconfig"), merged_defconfig)

      {output, 0} = System.cmd(ctng, ["defconfig"], cd: tmp_dir, stderr_to_stdout: true)
      _ = output

      config = File.read!(Path.join(tmp_dir, ".config"))
      ToolchainDefconfig.validate!(config_path, Path.join(tmp_dir, ".config"))
      {toolchain, extract_versions(config)}
    after
      File.rm_rf!(tmp_dir)
    end
  end

  defp merge_defconfigs(config_path) do
    [config_path, @host_fragment]
    |> Enum.map(&File.read!/1)
    |> Enum.join("\n")
  end

  defp extract_versions(config) do
    versions =
      Regex.scan(~r/^(CT_[A-Z0-9_]+VERSION)="([^"]+)"$/m, config, capture: :all_but_first)
      |> Enum.reject(fn [key, _value] -> MapSet.member?(@excluded_version_keys, key) end)
      |> Map.new(fn [key, value] -> {key, value} end)

    ordered_keys =
      @preferred_order ++
        (versions
         |> Map.keys()
         |> Enum.reject(&(&1 in @preferred_order))
         |> Enum.sort())

    ordered_keys
    |> Enum.flat_map(fn key ->
      case Map.fetch(versions, key) do
        {:ok, value} -> [{Map.get(@labels, key, key), value}]
        :error -> []
      end
    end)
  end

  defp render(version_metadata) do
    entries =
      version_metadata
      |> Enum.sort_by(fn {app_name, _versions} -> app_name end)
      |> Enum.map_join(",\n", fn {app_name, versions} ->
        rendered_versions =
          versions
          |> Enum.map_join(",\n", fn {component, version} ->
            "    {#{inspect(component)}, #{inspect(version)}}"
          end)

        "  #{inspect(app_name)} => [\n#{rendered_versions}\n  ]"
      end)

    """
    # Generated by update_versions.exs
    %{
    #{entries}
    }
    """
  end
end

ToolchainVersionUpdater.main(System.argv())
